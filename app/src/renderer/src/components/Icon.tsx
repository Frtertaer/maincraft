export type IconName = keyof typeof ICONS

const OPACITY: Record<string, number> = { '#': 1, '+': 0.6, '=': 0.32 }

function buildRects(rows: readonly string[]): Array<{ x: number; y: number; w: number; o: number }> {
  const rects: Array<{ x: number; y: number; w: number; o: number }> = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      if (!OPACITY[ch]) {
        x++
        continue
      }
      let w = 1
      while (x + w < row.length && row[x + w] === ch) w++
      rects.push({ x, y, w, o: OPACITY[ch] })
      x += w
    }
  })
  return rects
}

const CACHE = new Map<IconName, ReturnType<typeof buildRects>>()

export const Icon = memo(function Icon({
  name,
  size = 20,
  className,
  title
}: {
  name: IconName
  size?: 10 | 20 | 30 | 40
  className?: string
  title?: string
}) {
  let rects = CACHE.get(name)
  if (!rects) {
    rects = buildRects(ICONS[name])
    CACHE.set(name, rects)
  }
  return (
    <svg
      className={`icon pixelated ${className ?? ''}`}
      width={size}
      height={size}
      viewBox="0 0 10 10"
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      fill="currentColor"
    >
      {title && <title>{title}</title>}
      {rects.map((r, i) => (
        <rect key={i} x={r.x} y={r.y} width={r.w} height={1} opacity={r.o === 1 ? undefined : r.o} />
      ))}
    </svg>
  )
})
